/**
 * R16.291：AI 路由 5xx 的标识串，按**成因**分家。
 *
 * 这两个字符串此前是同一个值，从四个路由的八处 catch 里手抄：
 * 「AI 服务暂时不可用，请稍后再试。」它把两种寿命完全不同的失败说成了一种——
 *
 * - `authUnavailable`：`getServerAuthUser()` 抛错。缺 Supabase env 时这是**永久状态**，
 *   部署不补配置就每一次都失败。「暂时」和「请稍后再试」都是假话：没有「稍后」，
 *   重试一万次也是同一个结果。这正是长期挂在 roadmap 上的生产 AI 上游 502 每次
 *   冒烟都报同一句话的原因——那句话替一个配置问题许了一个它兑现不了的结局。
 * - `upstreamUnavailable`：上游模型端点抽风。**这一种才是真的暂时**，所以
 *   「请稍后再试」对它成立。
 *
 * 同一句话此前也让这两个成因没法分别观测：契约测试只能断言「有 502」，不能断言
 * 「这 502 是哪一种」，于是把配置缺失造成的 502 记成上游故障，记了好几轮。
 * 拆开之后 `scripts/ai-server-errors-claims.test.mjs` 才有可断言的东西：
 * 每一处 5xx 必须落在 SERVER_ERRORS 的某一把键上，而**永久性的那把键不许带
 * 「暂时 / 请稍后」**——这条判据反过来护住的是句子的诚实，不只是去重。
 *
 * 为什么不用字典（`i18n.ts`）：这些串与 `BODY_ERRORS` 同族，都是给开发者看的
 * 标识串，界面上不渲染（`ai-chat.tsx` 对 ≥500 一律换成本地化的 `dict.errorServer`）。
 * 把它们放进字典只会多一份需要 `check:dead-copy` 记账的副本。
 */

/**
 * 永久性失败：鉴权服务本身不可用（配置缺失、上游 Auth API 异常）。
 * 措辞**不含**「暂时」「请稍后」——见文件头的理由。
 */
export const SERVER_ERRORS = {
  /**
   * 鉴权不可用。这一支对四个路由的语义并不一样：
   * - `chat` / `summary`：鉴权只用来分限流桶，身份不可信时退化成游客桶即可
   *   （`resolveAuthUser` 的文档已经说明「没有会话 cookie」是游客的正常状态，
   *   抛出来的都是「身份不可信」而不是「没有身份」）。游客本来就能用这两个端点，
   *   所以整条功能线仍然可用，把它报成 502 是把一次降级说成了一次不可用。
   * - `plan` / `quiz`：这两个端点登录才可用（`if (!user) return 401`），
   *   身份不可信时不能当成游客放行，必须报出来——但报出来的理由是「查不到你是谁」，
   *   不是「AI 暂时不可用」。
   * 两条路的共同点是：这一句不该承诺「稍后」会好。
   */
  authUnavailable: "AI 服务鉴权不可用：无法确认请求方身份。",
  /** 上游模型端点不可用——**这一种才是暂时性故障**，措辞允许承诺「稍后重试」。 */
  upstreamUnavailable: "AI 上游暂时不可用，请稍后再试。",
} as const;

export type ServerErrorKey = keyof typeof SERVER_ERRORS;
