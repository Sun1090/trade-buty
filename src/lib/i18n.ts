export function getDict(locale: string | undefined): Dict {
  return DICTS[(locale as Locale) ?? DEFAULT_LOCALE] ?? DICTS[DEFAULT_LOCALE];
}

export function isLocale(v: string): v is Locale {
  return (LOCALES as string[]).includes(v);
}
